    t = i / DRUM_FS
    v = 82.0 * math.exp(-t / 0.05) * random.uniform(-1.0, 1.0) + 42.0 * math.exp(-t / 0.03) * math.sin(2.0 * math.pi * 185.0 * t)
    snare.append(s8(v))
