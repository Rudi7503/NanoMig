"""
Generates argon_data.i for argon_demo.s
(NanoMig / MiSTer 1-Minute Extended-HAM04 & 32-Channel DSP Grand Demo).

Clock note (32CH core, mister/rtl/audio_ext.v):
  Virtual 50 MHz timebase with 32 TDM slots (16 * virtual_ticks per 32 clocks):
  Fs = 25 MHz / PER  (PER = 521 -> 47,985 Hz ~ 48 kHz).
"""
import math
import random

CLK = 25e6
random.seed(7503)
out = []


def emit(s=""):
    out.append(s)


def words(label, vals, per_line=8):
    if label:
        emit(f"{label}:")
    for i in range(0, len(vals), per_line):
        emit("    DC.W    " + ",".join(f"${v & 0xFFFF:04X}" for v in vals[i:i + per_line]))


def longs(label, vals, per_line=6):
    if label:
        emit(f"{label}:")
    for i in range(0, len(vals), per_line):
        emit("    DC.L    " + ",".join(f"${v & 0xFFFFFFFF:08X}" for v in vals[i:i + per_line]))


def bytes_(label, vals, per_line=16):
    if label:
        emit(f"{label}:")
    for i in range(0, len(vals), per_line):
        emit("    DC.B    " + ",".join(f"${v & 0xFF:02X}" for v in vals[i:i + per_line]))


def s8(x):
    return max(-128, min(127, int(round(x))))


def s16(x):
    return max(-32768, min(32767, int(round(x))))


def midi_hz(n):
    return 440.0 * (2.0 ** ((n - 69.0) / 12.0))


def per_for(hz, n_samples):
    p = int(round(CLK / (hz * n_samples)))
    return max(32, min(65535, p))


def per_note(n, n_samples, detune_cents=0.0):
    return per_for(midi_hz(n) * (2.0 ** (detune_cents / 1200.0)), n_samples)


def vol(l, r):
    l = max(0, min(255, int(round(l))))
    r = max(0, min(255, int(round(r))))
    return (l << 8) | r


def q14(x):
    v = int(round(x * 16384.0))
    return max(-32768, min(32767, v))


def rbj(kind, f_norm, q):
    w0 = 2.0 * math.pi * f_norm
    c, s = math.cos(w0), math.sin(w0)
    a = s / (2.0 * q)
    if kind == "lp":
        b0, b1, b2 = (1.0 - c) / 2.0, 1.0 - c, (1.0 - c) / 2.0
    elif kind == "hp":
        b0, b1, b2 = (1.0 + c) / 2.0, -(1.0 + c), (1.0 + c) / 2.0
    elif kind == "bp":
        b0, b1, b2 = a, 0.0, -a
    else:
        raise ValueError(kind)
    a0, a1, a2 = 1.0 + a, -2.0 * c, 1.0 - a
    return [q14(b0 / a0), q14(b1 / a0), q14(b2 / a0), q14(a1 / a0), q14(a2 / a0)]


emit("; ======================================================================")
emit("; argon_data.i -- GENERATED by gen_argon_data.py")
emit(f"; Period clock: {CLK:.0f} Hz (Fs = 25 MHz / PER, 521 = 48 kHz)")
emit("; ======================================================================")
emit()

DRUM_FS = 22050.0
ENV_FS = 6000.0
emit(f"PER_48K         EQU {per_for(48000.0, 1)}")
emit(f"PER_DRUM        EQU {per_for(DRUM_FS, 1)}")
emit(f"PER_ENV         EQU {per_for(ENV_FS, 1)}")
emit()

# ---------------------------------------------------------------- Act I: 32-Voice Deep Note (350 glide frames + 150 hold frames = 10s)
GLIDE_FRAMES = 350
HOLD_FRAMES = 150
emit(f"ACT1_GLIDE      EQU {GLIDE_FRAMES}")
emit(f"ACT1_HOLD       EQU {HOLD_FRAMES}")

TARGET_NOTES = [38, 45, 50, 53, 57, 60, 62, 64, 65, 69, 72, 74, 76, 77, 81]
sa = []
for i in range(31):
    target = TARGET_NOTES[(i * len(TARGET_NOTES)) // 31]
    cents = ((-1) ** i) * (4.0 + 3.0 * (i % 3))
    p1 = per_note(target, 32, cents)
    p0 = per_note(random.uniform(54.0, 67.0), 32)
    delta = int(round((p1 - p0) * 65536.0 / GLIDE_FRAMES))
    side = (i / 30.0) * 0.48
    pan = 0.5 + side if (i % 2) else 0.5 - side
    v = vol(42 * (1.0 - pan) + 6, 42 * pan + 6)
    sa.append((p0, p1, delta, v, i * 1100))

words("SA_StartPer", [x[0] for x in sa])
words("SA_EndPer", [x[1] for x in sa])
longs("SA_Delta", [x[2] for x in sa])
words("SA_Vol", [x[3] for x in sa])
words("SA_Delay", [x[4] for x in sa])
emit(f"SUB_PER_D1      EQU {per_note(26, 64)}")  # Deep D1 on 64-sample 16-bit sine
emit()

# ---------------------------------------------------------------- Act II & IV: Music Sequencer Tables
ROOTS = [0, -4, 3, -2]          # Dm, Bb, F, C
ACID_BASE = 38                  # D2
ACID = [
    (0, 1), (0, 0), (12, 0), (0, 0), (None, 0), (0, 0), (3, 1), (0, 0),
    (-2, 0), (0, 0), (12, 1), (None, 0), (0, 0), (7, 0), (0, 0), (10, 1)
]
acid_per, acid_vol = [], []
for bar in range(4):
    for st, (o, acc) in enumerate(ACID):
        if o is None:
            acid_per.append(0)
            acid_vol.append(0)
        else:
            acid_per.append(per_note(ACID_BASE + ROOTS[bar] + o, 64))  # 64-sample 16-bit Saw!
            acid_vol.append(vol(165, 165) if acc else vol(105, 105))
words("AcidPerSeq", acid_per)
words("AcidVolSeq", acid_vol)
emit()

LEAD = [
    69, 0, 72, 74, 0, 72, 69, 0, 67, 0, 65, 67, 69, 0, 65, 0,
    65, 0, 70, 74, 0, 72, 70, 0, 69, 0, 67, 65, 67, 0, 62, 0,
    72, 0, 69, 65, 0, 69, 72, 0, 77, 0, 76, 72, 74, 0, 69, 0,
    74, 0, 72, 67, 0, 64, 67, 0, 72, 0, 76, 79, 76, 0, 74, 0
]
words("LeadPerSeq", [per_note(n, 64) if n else 0 for n in LEAD])
emit()

BELLS = {0: 74, 6: 81, 12: 77, 16: 74, 24: 70, 32: 77, 38: 84, 44: 79, 48: 76, 56: 79}
bell = []
for st in range(64):
    if st in BELLS:
        hz = midi_hz(BELLS[st])
        bell += [per_for(hz, 64), per_for(hz * math.sqrt(2.0), 16)]
    else:
        bell += [0, 0]
words("BellPerSeq", bell)
emit()

# 8-voice Arp/Brass Chords (Voices 13..20) for Act IV
ARP_CHORDS = [
    [62, 65, 69, 74, 62, 65, 69, 74],  # Dm9
    [58, 62, 65, 70, 58, 62, 65, 70],  # BbMaj7
    [60, 65, 69, 72, 60, 65, 69, 72],  # FMaj7
    [60, 64, 67, 72, 60, 64, 67, 72],  # C6
]
arp_per = []
for chd in ARP_CHORDS:
    for idx, n in enumerate(chd):
        det = -9.0 if idx < 4 else +9.0
        arp_per.append(per_note(n, 64, det))
words("ArpChordPer", arp_per)

arp_vol = []
for i in range(8):
    pan = i / 7.0
    arp_vol.append(vol(36 * (1.0 - pan) + 8, 36 * pan + 8))
words("ArpVolTab", arp_vol)
