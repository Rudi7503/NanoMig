# 16-bit Big-Endian waveforms (64 words = 128 bytes)
saw16_64 = [s16(24000.0 - 48000.0 * i / 63.0) for i in range(64)]
sine16_64 = [s16(24000.0 * math.sin(2.0 * math.pi * i / 64.0)) for i in range(64)]
words("Saw16_64", saw16_64)
words("Sine16_64", sine16_64)

# 8-bit waveforms
saw32 = [s8(100 - 200 * i / 31.0) for i in range(32)]
saw64 = [s8(100 - 200 * i / 63.0) for i in range(64)]
saw256 = [s8(90 - 180 * i / 255.0) for i in range(256)]
sine64 = [s8(100 * math.sin(2.0 * math.pi * i / 64.0)) for i in range(64)]
