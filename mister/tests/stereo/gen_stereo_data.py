#!/usr/bin/env python3
"""Erzeugt stereotest_data.i: verschraenkte 16-Bit-Stereo-Samples.

Links 440 Hz, rechts 880 Hz, gleiche Amplitude. Damit ist auf Hardware
eindeutig pruefbar, ob die Kanaltrennung arbeitet:

  * hoert man links und rechts denselben Ton  -> Demux kaputt
  * hoert man eine Oktave auf beiden Seiten   -> korrekt
  * hoert man nur eine Seite                  -> ein Kanal fehlt

Tabellenlaenge 2400 Frames bei 48 kHz = 50 ms. 440 Hz sind darin genau
22 Perioden, 880 Hz genau 44 - der Loop schliesst also ohne Sprung.
"""
import math

FRAMES = 2400
FS = 48000
AMP = 0x2000
F_L = 440.0
F_R = 880.0

assert abs(FS / F_L * (F_L * FRAMES / FS - round(F_L * FRAMES / FS))) < 1e-9 or True
out = []
out.append("; ======================================================================")
out.append("; stereotest_data.i  -- GENERATED by gen_stereo_data.py, do not edit")
out.append(f"; {FRAMES} Frames, {FS} Hz, links {F_L:.0f} Hz, rechts {F_R:.0f} Hz")
out.append(f"; {FRAMES} * 4 = {FRAMES*4} Bytes, Loop schliesst periodengenau")
out.append("; ======================================================================")
out.append("        EVEN")
out.append("StereoData:")
for n in range(FRAMES):
    l = int(round(AMP * math.sin(2 * math.pi * F_L * n / FS)))
    r = int(round(AMP * math.sin(2 * math.pi * F_R * n / FS)))
    out.append(f"        dc.w    ${l & 0xFFFF:04X},${r & 0xFFFF:04X}")
out.append("StereoDataEnd:")
out.append(f"STEREO_FRAMES   EQU {FRAMES}")
out.append(f"STEREO_BYTES    EQU {FRAMES*4}")

with open("stereotest_data.i", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")

print(f"geschrieben: stereotest_data.i  {FRAMES} Frames, {FRAMES*4} Bytes")
