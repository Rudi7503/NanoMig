#!/usr/bin/env python3
"""Erzeugt am_data.i: Traeger 2 Hz (langsam abgespielt) und Ton 440 Hz.

Der Traeger wird als ein Sinuszyklus gespeichert und mit einer viertausend-
fachen Periodendauer abgespielt. Damit braucht 2 Hz nur 2400 Samples statt
24000 und die Datei bleibt klein.

  Traeger  1 Periode 2 Hz, 2400 Samples, gespielt mit PER = 5208  -> 4,8 kHz
           ergibt 4800 / 2400 = 2 Hz
  Ton      440 Hz bei 48 kHz, 2400 Samples = 22 Perioden
"""
import math

FRAMES = 2400
AMP = 0x1800

out = []
out.append("; ======================================================================")
out.append("; am_data.i  -- GENERATED by gen_am_data.py, do not edit")
out.append(f"; Traeger 2 Hz (2400 Samples bei 4,8 kHz), Ton 440 Hz (2400 Samples bei 48 kHz)")
out.append("        EVEN")
out.append("AmCarrier:")
for n in range(FRAMES):
    v = int(round(AMP * math.sin(2 * math.pi * n / FRAMES)))
    out.append(f"        dc.w    ${v & 0xFFFF:04X},${v & 0xFFFF:04X}")
out.append("AmCarrierEnd:")
out.append("AmTone:")
for n in range(FRAMES):
    v = int(round(AMP * math.sin(2 * math.pi * 440.0 * n / 48000.0)))
    out.append(f"        dc.w    ${v & 0xFFFF:04X},${v & 0xFFFF:04X}")
out.append("AmToneEnd:")
out.append(f"AM_FRAMES       EQU {FRAMES}")
out.append(f"AM_CARRIER_BYTES EQU {FRAMES*4}")
out.append(f"AM_TONE_BYTES    EQU {FRAMES*4}")
out.append("AM_PER_CARRIER  EQU 5208        ; 25 MHz / 5208 = 4,8 kHz, /2400 = 2 Hz")
out.append("AM_PER_TONE     EQU 521         ; 25 MHz / 521 = 48 kHz")

with open("am_data.i", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print(f"geschrieben: am_data.i  {FRAMES} Frames je Signal")
