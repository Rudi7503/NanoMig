#!/usr/bin/env python3
"""Erzeugt rechteck_data.i: Rechteck 200 Hz plus Tiefpasskoeffizienten.

Zweck: beweisen, dass die Filterkette die Oberschwingungen entfernt.

  ch0      Rechteck 200 Hz, Vollaussteuerung, beide Kanaele
  ch1..31  Tiefpass 300 Hz, Quelle = Vorgaenger nach Filter

Warum 300 Hz Grenzfrequenz:
  Grundwelle 200 Hz liegt darunter und kommt durch (rund 0,91 je Stufe,
  32 Stufen also etwa 5 Prozent).
  Die erste Oberschwingung bei 600 Hz liegt eine Oktave darueber und wird
  je Stufe um rund 12 dB gedaempft - nach 32 Stufen ist sie verschwunden.

Ergebnis: der Ausgang ist ein Sinus bei 200 Hz. Nachweis ueber die
Amplitudeverteilung, nicht ueber das Gehoer.
"""
import math

FS = 48000
FRAMES = 2400          # 10 volle Perioden bei 200 Hz
F_SQUARE = 200.0
AMP = 0x1FFF
FC = 300.0
Q = 0.707

# Auf ganze Samples, damit der Loop ohne Sprung schliesst
PERIOD = int(round(FS / F_SQUARE))     # 240
assert FRAMES % PERIOD == 0, "Frames muessen ganze Perioden sein"

w0 = 2 * math.pi * FC / FS
alpha = math.sin(w0) / (2 * Q)
cosw0 = math.cos(w0)
b0 = (1 - cosw0) / 2
b1 = 1 - cosw0
b2 = b0
a0 = 1 + alpha
a1 = -2 * cosw0
a2 = 1 - alpha

def q14(x):
    v = int(round(x / a0 * 16384))
    return max(-32768, min(32767, v))

coef = {
    "BQ_B0": q14(b0), "BQ_B1": q14(b1), "BQ_B2": q14(b2),
    "BQ_A1": q14(a1), "BQ_A2": q14(a2),
}

out = []
out.append("; ======================================================================")
out.append("; rechteck_data.i  -- GENERATED by gen_rechteck_data.py, do not edit")
out.append(f"; Rechteck {F_SQUARE:.0f} Hz, {FRAMES} Frames, {PERIOD} Samples je Periode")
out.append(f"; Tiefpass je Stufe: {FC:.0f} Hz, Q={Q}")
for k, v in coef.items():
    out.append(f"{k:<8}EQU ${v & 0xFFFF:04X}    ; {v}")
out.append("        EVEN")
out.append("RechteckData:")
half = PERIOD // 2
for n in range(FRAMES):
    v = AMP if (n % PERIOD) < half else -AMP
    out.append(f"        dc.w    ${v & 0xFFFF:04X},${v & 0xFFFF:04X}")
out.append("RechteckDataEnd:")
out.append(f"RECHTECK_FRAMES EQU {FRAMES}")
out.append(f"RECHTECK_BYTES  EQU {FRAMES*4}")

with open("rechteck_data.i", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")

print(f"geschrieben: rechteck_data.i  {FRAMES} Frames, Periode {PERIOD} Samples")
for k, v in coef.items():
    print(f"  {k} = {v}")
