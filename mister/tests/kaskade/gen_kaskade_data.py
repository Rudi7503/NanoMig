#!/usr/bin/env python3
"""Erzeugt kaskade_data.i: Rauschen plus Filterkoeffizienten fuer 32 Stufen.

Zweck: den extremen Tiefpass pruefen. 32 identische Biquad-Stufen in Reihe
ergeben rund 384 dB/Oktave. Auf Rauschen gehoert das wie ein sehr dunkles
Rauschen, und die Kaskade darf nicht schwingen oder clippen.

Erzeugt:
  KaskadeData          verschraenktes Stereo-Rauschen, 2400 Frames
  KASKADE_FRAMES       Anzahl Frames
  KASKADE_BYTES        Laenge in Bytes
  BQ_B0..BQ_A2         Koeffizienten einer Stufe, Q2.14
"""
import math
import random

FRAMES = 2400
FS = 48000
AMP = 0x1000          # bewusst nicht Vollaussteuerung
FC = 8000.0           # Grenzfrequenz einer Stufe (hoerbar auch nach 32 Stufen)
Q = 0.707

# RBJ-Biquad, Tiefpass
w0 = 2 * math.pi * FC / FS
alpha = math.sin(w0) / (2 * Q)
cosw0 = math.cos(w0)
b0 = (1 - cosw0) / 2
b1 = 1 - cosw0
b2 = b0
a0 = 1 + alpha
a1 = -2 * cosw0
a2 = 1 - alpha

def q14(x):
    v = int(round(x / a0 * 16384))
    return max(-32768, min(32767, v))

coef = {
    "BQ_B0": q14(b0), "BQ_B1": q14(b1), "BQ_B2": q14(b2),
    "BQ_A1": q14(a1), "BQ_A2": q14(a2),
}

random.seed(4711)      # reproduzierbar
out = []
out.append("; ======================================================================")
out.append("; kaskade_data.i  -- GENERATED by gen_kaskade_data.py, do not edit")
out.append(f"; {FRAMES} Frames Rauschen, {FS} Hz, eine Stufe {FC:.0f} Hz Q={Q}")
out.append("; 32 Stufen in Reihe = rund 384 dB/Oktave")
for k, v in coef.items():
    out.append(f"{k:<8}EQU ${v & 0xFFFF:04X}    ; {v}")
out.append("        EVEN")
out.append("KaskadeData:")
for n in range(FRAMES):
    l = int(AMP * (random.random() * 2 - 1))
    r = int(AMP * (random.random() * 2 - 1))
    out.append(f"        dc.w    ${l & 0xFFFF:04X},${r & 0xFFFF:04X}")
out.append("KaskadeDataEnd:")
out.append(f"KASKADE_FRAMES  EQU {FRAMES}")
out.append(f"KASKADE_BYTES   EQU {FRAMES*4}")

with open("kaskade_data.i", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")

print("geschrieben: kaskade_data.i")
for k, v in coef.items():
    print(f"  {k} = {v}")
