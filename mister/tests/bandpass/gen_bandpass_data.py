#!/usr/bin/env python3
"""Erzeugt bandpass_data.i: Rechteck 200 Hz plus Bandpasskoeffizienten 1 kHz.

Das Rechteck bei 200 Hz hat Harmonische bei 200, 600, 1000, 1400 Hz ...
Die 5. Harmonische liegt exakt bei 1000 Hz. Ein Bandpass bei 1 kHz holt
genau sie heraus, der Ausgang ist ein Sinus bei 1 kHz.

Nachweis ohne Frequenzanalyse: Nulldurchgaenge zaehlen.
  1024 Samples bei 48 kHz = 21,33 ms  ->  21,33 Perioden  ->  42,7 Wechsel
  Sinus       rund 42
  Rauschen    rund 500
  Stille      0
"""
import math

FS = 48000
FRAMES = 2400
F_SQUARE = 200.0
AMP = 0x1FFF
F_CENTER = 1000.0
Q = 0.707          # breitbandig je Stufe; 32 Stufen verengen auf rund 250 Hz

PERIOD = int(round(FS / F_SQUARE))
assert FRAMES % PERIOD == 0

w0 = 2 * math.pi * F_CENTER / FS
alpha = math.sin(w0) / (2 * Q)
cosw0 = math.cos(w0)
b0 = alpha
b1 = 0.0
b2 = -alpha
a0 = 1 + alpha
a1 = -2 * cosw0
a2 = 1 - alpha

def q14(x):
    v = int(round(x / a0 * 16384))
    return max(-32768, min(32767, v))

coef = {
    "BQ_B0": q14(b0), "BQ_B1": q14(b1), "BQ_B2": q14(b2),
    "BQ_A1": q14(a1), "BQ_A2": q14(a2),
}

out = []
out.append("; ======================================================================")
out.append("; bandpass_data.i  -- GENERATED by gen_bandpass_data.py, do not edit")
out.append(f"; Rechteck {F_SQUARE:.0f} Hz  ->  Bandpass {F_CENTER:.0f} Hz, Q={Q}")
out.append(f"; {FRAMES} Frames, {PERIOD} Samples je Periode")
out.append("; Erwartung: Sinus 1 kHz, rund 42 Nulldurchgaenge je 1024 Samples")
for k, v in coef.items():
    out.append(f"{k:<8}EQU ${v & 0xFFFF:04X}    ; {v}")
out.append("        EVEN")
out.append("BandpassData:")
half = PERIOD // 2
for n in range(FRAMES):
    v = AMP if (n % PERIOD) < half else -AMP
    out.append(f"        dc.w    ${v & 0xFFFF:04X},${v & 0xFFFF:04X}")
out.append("BandpassDataEnd:")
out.append(f"BANDPASS_FRAMES EQU {FRAMES}")
out.append(f"BANDPASS_BYTES  EQU {FRAMES*4}")

with open("bandpass_data.i", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")

print(f"geschrieben: bandpass_data.i  {FRAMES} Frames")
for k, v in coef.items():
    print(f"  {k} = {v}")
