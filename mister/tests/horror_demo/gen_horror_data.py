"""
Generates horror_data.i for horror_demo.s
(NanoMig 32-Channel Audio & Gothic Horror Grand Testcase).

Showcases:
  - 32 Hardware Voices
  - Approaching Footsteps with Multi-Tap Hardware Start-Delay ($DFF41C)
  - Ghostly Corridor Howling using 24 dB Cascaded Moog Filters & Sweeps
  - Hardware AM / Tremolo (Fluttering Bat Wings)
  - Hardware Ringmodulation (Eerie Ghost Moans & Demonic Skeleton Laugh)
  - 4-Bit ADPCM Dungeon Water Drops
  - True-Peak Master-Mixer Headroom (+36 dB) & AGC Limiter
  - Gothic Vampire Hallway, 32 Bats Swarm, and Laughing Skeleton Graphics!

Virtual 25 MHz Timebase (audio_ext.v):
  Fs = 25 MHz / PER  (521 = 48 kHz, 1042 = 24 kHz, 1134 = 22.05 kHz).
All 16-bit PCM data is strictly Motorola Big-Endian (>i2)!
"""

import math
import struct
import random

CLK = 25e6
random.seed(666)

out = []

def emit(s=""):
    out.append(s)

def words(label, vals, per_line=8):
    if label:
        emit(f"{label}:")
    for i in range(0, len(vals), per_line):
        emit("    DC.W    " + ",".join(f"${v & 0xFFFF:04X}" for v in vals[i:i + per_line]))

def bytes_(label, vals, per_line=16):
    if label:
        emit(f"{label}:")
    for i in range(0, len(vals), per_line):
        emit("    DC.B    " + ",".join(f"${v & 0xFF:02X}" for v in vals[i:i + per_line]))

def s16(x):
    return max(-32768, min(32767, int(round(x))))

def per_for(hz, n_samples=1):
    p = int(round(CLK / (hz * n_samples)))
    return max(32, min(65535, p))

def q14(x):
    v = int(round(x * 16384.0))
    return max(-32768, min(32767, v))

def rbj(kind, f_norm, q):
    f_norm = max(0.001, min(0.48, f_norm))
    w0 = 2.0 * math.pi * f_norm
    c, s = math.cos(w0), math.sin(w0)
    a = s / (2.0 * q)
    if kind == "lp":
        b0, b1, b2 = (1.0 - c) / 2.0, 1.0 - c, (1.0 - c) / 2.0
    elif kind == "hp":
        b0, b1, b2 = (1.0 + c) / 2.0, -(1.0 + c), (1.0 + c) / 2.0
    elif kind == "bp":
        b0, b1, b2 = a, 0.0, -a
    else:
        raise ValueError(kind)
    a0, a1, a2 = 1.0 + a, -2.0 * c, 1.0 - a
    return [q14(b0 / a0), q14(b1 / a0), q14(b2 / a0), q14(a1 / a0), q14(a2 / a0)]

emit("; ======================================================================")
