# (A) Footstep Sample: Sharp stone heel impact + textured stone echo decay
# Length: 3000 samples @ 24 kHz (~125 ms = 6000 bytes)
fs_foot = 24000.0
n_foot = 3000
foot_samples = []
for i in range(n_foot):
    t = i / fs_foot
    # Sharp transient impact (5 ms)
    impact = math.sin(2.0 * math.pi * 140.0 * t) * math.exp(-t * 250.0)
    # Scrape / grit texture (random noise filtered)
    grit = (random.random() * 2.0 - 1.0) * math.exp(-t * 80.0) * 0.7
    # Heel click (high frequency tap)
    click = math.sin(2.0 * math.pi * 1200.0 * t) * math.exp(-t * 500.0) * 0.5
    val = (impact * 0.6 + grit * 0.4 + click * 0.3) * 32000.0
    foot_samples.append(s16(val))

emit("; Footstep Sample (24 kHz, 16-Bit Big-Endian, 3000 words = 6000 bytes)")
emit("HORROR_FOOT_LEN EQU 6000")
words("HorrorFootstepData", foot_samples)
