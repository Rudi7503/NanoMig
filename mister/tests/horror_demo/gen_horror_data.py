# Generate stylized skull bitmap (bone ivory + dark eye sockets + glowing red embers)
for y in range(24):
    for x in range(32):
        dx = x - 15.5
        dy = y - 11.0
        # Oval skull shape
        dist = (dx * dx) / (11.0 * 11.0) + (dy * dy) / (10.0 * 10.0)
