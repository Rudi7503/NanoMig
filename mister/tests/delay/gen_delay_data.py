#!/usr/bin/env python3
"""Erzeugt delay_data.i: 200 ms Rechteck 200 Hz fuer den Verzoegerungstest.

Alle 32 Stimmen teilen sich denselben Puffer. Jede startet spaeter als die
vorige: ch0 sofort, ch1 nach 10 ms, ch2 nach 20 ms ... ch31 nach 310 ms.
Jede Stufe mit 90 Prozent der Lautstaerke der vorigen.
"""
FS = 48000
FRAMES = 9600          # 200 ms
F_SQUARE = 200.0
AMP = 0x1FFF
PERIOD = int(round(FS / F_SQUARE))
assert FRAMES % PERIOD == 0, "Frames muessen ganze Perioden sein"

DELAY_TICK_US = 30.52  # 32.768 kHz

out = []
out.append("; ======================================================================")
out.append("; delay_data.i  -- GENERATED by gen_delay_data.py, do not edit")
out.append(f"; Rechteck {F_SQUARE:.0f} Hz, {FRAMES} Frames = 200 ms")
out.append("; 32 Stimmen, je 10 ms spaeter, je 90 Prozent leiser")
for n in range(32):
    d = int(round(n * 10.0 / (DELAY_TICK_US / 1000.0)))
    out.append(f"DELAY_{n:<2}         EQU {d:<6} ; {n*10} ms")
out.append("        EVEN")
out.append("DelayData:")
half = PERIOD // 2
for n in range(FRAMES):
    v = AMP if (n % PERIOD) < half else -AMP
    out.append(f"        dc.w    ${v & 0xFFFF:04X},${v & 0xFFFF:04X}")
out.append("DelayDataEnd:")
out.append(f"DELAY_FRAMES    EQU {FRAMES}")
out.append(f"DELAY_BYTES     EQU {FRAMES*4}")

with open("delay_data.i", "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")

print(f"geschrieben: delay_data.i  {FRAMES} Frames, {DELAY_TICK_US} us je Tick")
print(f"  ch0 Verzoegerung 0, ch31 {int(round(31*10/(DELAY_TICK_US/1000)))} Ticks")
